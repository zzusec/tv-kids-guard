    private static volatile KeyStore store;

    private UpdateTrust() {}

    /** Platform trust store plus the public GitHub roots; safe to call from any thread. */
    static KeyStore store() throws IOException {
        KeyStore existing = store;
        if (existing != null) {
            return existing;
        }
        synchronized (UpdateTrust.class) {
            if (store == null) {
                store = build();
            }
            return store;
        }
    }

    private static KeyStore build() throws IOException {
        try {
            KeyStore trust = KeyStore.getInstance(KeyStore.getDefaultType());
            trust.load(null, null);
            for (Certificate certificate : embedded()) {
                X509Certificate root = (X509Certificate) certificate;
                trust.setCertificateEntry(root.getSubjectX500Principal().getName(), root);
            }
            return trust;
        } catch (GeneralSecurityException e) {
            throw new IOException("无法加载更新根证书", e);
        }
    }

    /** Parses every certificate in a PEM bundle; kept package-visible for tests. */
    static Collection<? extends Certificate> readPem(CertificateFactory factory, InputStream input)
            throws CertificateException {
        Collection<? extends Certificate> certificates = factory.generateCertificates(input);
        if (certificates.isEmpty()) {
            throw new CertificateException("证书文件为空");
        }
        return certificates;
    }

    static byte[] pemBytes() {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        for (String block : PEM) {
            out.writeBytes(("-----BEGIN CERTIFICATE-----\n" + block
                    + "\n-----END CERTIFICATE-----\n").getBytes(StandardCharsets.US_ASCII));
        }
        return out.toByteArray();
    }

    static Collection<? extends Certificate> embedded() throws CertificateException {
        return readPem(CertificateFactory.getInstance("X.509"),
                new ByteArrayInputStream(pemBytes()));
    }
